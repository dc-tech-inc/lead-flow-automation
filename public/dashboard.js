/* Renders /api/metrics. All text goes through textContent, never innerHTML. */
const SVG_NS = "http://www.w3.org/2000/svg";
const $ = (id) => document.getElementById(id);

function duration(sec) {
  if (sec === null || sec === undefined) return "n/a";
  if (sec < 60) return `${Math.round(sec)}s`;
  const min = Math.round(sec / 60);
  if (min < 60) return `${min}m`;
  return `${Math.floor(min / 60)}h ${String(min % 60).padStart(2, "0")}m`;
}

const percent = (x) => `${(x * 100).toFixed(1)}%`;

function svg(tag, attrs, text) {
  const el = document.createElementNS(SVG_NS, tag);
  for (const [k, v] of Object.entries(attrs)) el.setAttribute(k, String(v));
  if (text !== undefined) el.textContent = text;
  return el;
}

function clear(el, keep) {
  for (const child of [...el.childNodes]) if (!keep.includes(child.nodeName)) child.remove();
}

function row(tbody, cells) {
  const tr = document.createElement("tr");
  cells.forEach(([text, num], i) => {
    const td = document.createElement(i === 0 ? "th" : "td");
    if (i === 0) td.scope = "row";
    if (num) td.className = "num";
    td.textContent = text;
    tr.append(td);
  });
  tbody.append(tr);
}

// The signature element: median and p90 placed on one shared time scale.
function drawRuler(m) {
  const el = $("ruler");
  clear(el, ["title"]);
  const max = Math.max(m.p90ResponseSec ?? 0, 60) * 1.15;
  const x = (s) => 12 + (s / max) * 576;
  el.append(svg("rect", { class: "track", x: 12, y: 24, width: 576, height: 8, rx: 4 }));
  if (m.medianResponseSec !== null) {
    el.append(svg("circle", { class: "marker-median", cx: x(m.medianResponseSec), cy: 28, r: 8 }));
    el.append(svg("text", { x: x(m.medianResponseSec), y: 56, "text-anchor": "middle" }, `median ${duration(m.medianResponseSec)}`));
  }
  if (m.p90ResponseSec !== null) {
    el.append(svg("circle", { class: "marker-p90", cx: x(m.p90ResponseSec), cy: 28, r: 8 }));
    el.append(svg("text", { x: x(m.p90ResponseSec), y: 12, "text-anchor": "middle" }, `p90 ${duration(m.p90ResponseSec)}`));
  }
  $("ruler-caption").textContent = "Half of responded leads were answered within the median; nine in ten within p90.";
}

function drawDaily(m) {
  const el = $("daily");
  clear(el, ["title"]);
  const days = m.daily;
  const max = Math.max(...days.map((d) => d.medianResponseSec ?? 0), 60);
  const left = 44, bottom = 170, height = 150, width = 720 - left - 8;
  const slot = width / Math.max(days.length, 1);
  el.append(svg("line", { class: "axis", x1: left, x2: 712, y1: bottom, y2: bottom }));
  el.append(svg("text", { x: left - 6, y: 24, "text-anchor": "end" }, duration(max)));
  el.append(svg("text", { x: left - 6, y: bottom, "text-anchor": "end" }, "0"));
  days.forEach((d, i) => {
    if (d.medianResponseSec === null) return;
    const h = (d.medianResponseSec / max) * height;
    const bar = svg("rect", { class: "bar", x: left + i * slot + slot * 0.15, y: bottom - h, width: slot * 0.7, height: h });
    bar.append(svg("title", {}, `${d.date}: ${duration(d.medianResponseSec)} (${d.leads} leads)`));
    el.append(bar);
  });
  if (days.length > 0) {
    el.append(svg("text", { x: left, y: 190 }, days[0].date));
    el.append(svg("text", { x: 712, y: 190, "text-anchor": "end" }, days[days.length - 1].date));
  }
}

function render(m) {
  $("hero-value").textContent = duration(m.medianResponseSec);
  $("kpi-p90").textContent = duration(m.p90ResponseSec);
  $("kpi-conv").textContent = percent(m.conversionRate);
  $("kpi-leads").textContent = String(m.leads);
  $("kpi-resp").textContent = String(m.responded);
  drawRuler(m);
  drawDaily(m);

  const daily = $("daily-table").tBodies[0];
  daily.replaceChildren();
  for (const d of m.daily) row(daily, [[d.date], [String(d.leads), true], [duration(d.medianResponseSec), true]]);

  const src = $("src-table").tBodies[0];
  src.replaceChildren();
  for (const s of m.bySource) row(src, [[s.source], [String(s.leads), true], [duration(s.medianResponseSec), true], [percent(s.conversionRate), true]]);

  const badge = $("dataset-badge");
  badge.hidden = m.dataset === "live";
  badge.textContent = m.dataset === "mixed" ? "Includes synthetic data" : "Synthetic data";
  $("footnote").textContent =
    m.dataset === "live"
      ? ""
      : "Synthetic data: generated by src/seed.ts with invented parameters. These figures show the pipeline working, not real performance.";
}

async function load() {
  const status = $("status");
  status.className = "status";
  status.textContent = "Loading metrics…";
  status.hidden = false;
  $("retry").hidden = true;
  $("content").hidden = true;
  try {
    const res = await fetch(`/api/metrics?days=${encodeURIComponent($("window").value)}`);
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    const m = await res.json();
    if (m.dataset === "empty") {
      status.textContent = "No leads in this window yet. Send a signed lead.created webhook or run the seed.";
      return;
    }
    render(m);
    status.hidden = true;
    $("content").hidden = false;
  } catch (err) {
    status.className = "status error";
    status.textContent = `Could not load metrics (${err.message}).`;
    $("retry").hidden = false;
  }
}

$("window").addEventListener("change", load);
$("retry").addEventListener("click", load);
load();
